package T3_Insertar;
public class T3_Insertar_JAVA
{
    public static void main(String[] args)
    {
        int[] numeros = {4,5,6,1,2,3,7,8,9};
        
        
        for (int i = 0; i < numeros.length; i++) 
        {
                System.out.print("[" + numeros[i] + "] ");
        }
    }
}